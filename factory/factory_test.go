func spec(t *testing.T, name string) ServiceSpec {
	t.Helper()
	s, err := LoadSpec(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	return s
}

// shared builds: compiling Go is the slow part, so build each intent once.
var shared = &Factory{}

func TestMain(m *testing.M) {
	dir, err := os.MkdirTemp("", "factory-test-builds-")
	if err != nil {
		panic(err)
	}
	shared.Root = dir
	code := m.Run()
	os.RemoveAll(dir)
	os.Exit(code)
}

func build(t *testing.T, s ServiceSpec) *Version {
	t.Helper()
	v, err := shared.Build(context.Background(), s)
	if err != nil {
		if v != nil {
			t.Log(v.Report())
		}
		t.Fatal(err)
	}
	return v
}

func TestIntentBuildsAVerifiedService(t *testing.T) {
	v := build(t, spec(t, "flags-v1.json"))
	if !v.Passed() || len(v.Results) != 9 {
		t.Fatalf("%s", v.Report())
	}
	if !strings.HasPrefix(v.Files["main.go"], "// Code generated by reversible/factory") ||
		!strings.Contains(v.Files["main.go"], "This file is a cache: change the intent, not the code.") {
		t.Fatal("generated code isn't marked as a cache")
	}
	again := build(t, spec(t, "flags-v1.json"))
	if !again.Cached || again.Binary != v.Binary {
		t.Fatal("the same intent should be served from the cache")
	}
}

func TestVagueIntentIsNotBuilt(t *testing.T) {
	s := spec(t, "flags-v1.json")
	s.Resource.Fields[0].Pattern = "^[a-z"
	s.Resource.Fields = append(s.Resource.Fields, Field{Name: "weight", Type: "int", Min: ptr(10), Max: ptr(1)})
	s.Resource.Rules = []Rule{{ForbidDeleteWhen: &Condition{Field: "status", Equals: "live"}}}
	s.Examples = append(s.Examples, Example{Name: "nonsense", Request: HTTPCall{Method: "PUT", Path: "/things"}, Expect: Expectancy{Status: 200}})
	_, err := (&Factory{Root: t.TempDir()}).Build(context.Background(), s)
	if !errors.Is(err, ErrNotReady) {
		t.Fatalf("err = %v", err)
	}
	for _, want := range []string{"not a valid regular expression", "no value satisfies both", `unknown field "status"`, "PUT /things is not an endpoint"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("missing question %q in:\n%v", want, err)
		}
	}
}

func TestClarifyingQuestions(t *testing.T) {
	s := spec(t, "flags-v1.json")
	s.Owner = ""
	s.Examples = s.Examples[:3] // no list or delete examples
	var asks []string
	for _, q := range s.Check() {
		if q.Severity != Clarify {
			t.Fatalf("unexpected blocking question: %v", q)
		}
		asks = append(asks, q.Ask)
	}
	joined := strings.Join(asks, "\n")
	for _, want := range []string{"who is accountable", "no example shows what list does", "no example shows what delete does"} {
		if !strings.Contains(joined, want) {
			t.Errorf("missing %q in:\n%s", want, joined)
		}
	}
}

func ptr(f float64) *float64 { return &f }

// teamTraffic is a morning of the platform team using v1.
var teamTraffic = []HTTPCall{
	{Method: "POST", Path: "/flags", Body: map[string]any{"key": "dark-mode", "owner": "web"}},
	{Method: "POST", Path: "/flags", Body: map[string]any{"key": "new-search", "owner": "search", "description": "vector search"}},
	{Method: "POST", Path: "/flags", Body: map[string]any{"key": "Beta", "owner": "web"}},
	{Method: "PATCH", Path: "/flags/dark-mode", Body: map[string]any{"enabled": true}},
	{Method: "GET", Path: "/flags/dark-mode"},
	{Method: "POST", Path: "/flags", Body: map[string]any{"key": "old-banner", "owner": "web"}},
	{Method: "DELETE", Path: "/flags/old-banner"},
	{Method: "PATCH", Path: "/flags/new-search", Body: map[string]any{"enabled": true, "rollout_percent": 25}},
	{Method: "DELETE", Path: "/flags/dark-mode"},
	{Method: "GET", Path: "/flags"},
}

func TestReleaseDiffAndRewind(t *testing.T) {
	ctx := context.Background()
	v1, v2 := build(t, spec(t, "flags-v1.json")), build(t, spec(t, "flags-v2.json"))
	if !v2.Passed() || len(v2.Results) != 12 {
		t.Fatalf("%s", v2.Report())
	}

	router := &Router{DataPath: filepath.Join(t.TempDir(), "flags.json")}
	defer router.Stop()
	prod := httptest.NewServer(router)
	defer prod.Close()
	rt := reversible.New()

	if _, err := rt.Execute(ctx, reversible.Intent{ID: "release-v1", Effects: []reversible.Effect{router.Release(v1)}}); err != nil {
		t.Fatal(err)
	}
	for _, c := range teamTraffic[:7] { // v1-era usage, with dark-mode still on
		if _, err := Call(ctx, prod.URL, c); err != nil {
			t.Fatal(err)
		}
	}

	// Behaviour diff on recorded traffic: every change explained by the intent.
	d, err := Diff(ctx, router.Traffic(), v1, v2)
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Changes) == 0 || len(d.Unexpected()) != 0 {
		t.Fatalf("diff:\n%s", d)
	}
	if !strings.Contains(d.String(), "new field rollout_percent") {
		t.Fatalf("diff:\n%s", d)
	}

	// State diff on production data written by v1: defaults applied on load.
	sd, err := DiffState(ctx, router.DataPath, v1, v2)
	if err != nil {
		t.Fatal(err)
	}
	if len(sd.Changes) == 0 || len(sd.Unexpected()) != 0 {
		t.Fatalf("state diff:\n%s", sd)
	}

	// Release v2; existing data keeps working; new rule is live.
	if _, err := rt.Execute(ctx, reversible.Intent{ID: "release-v2", Effects: []reversible.Effect{router.Release(v2)}}); err != nil {
		t.Fatal(err)
	}
	got, _ := Call(ctx, prod.URL, HTTPCall{Method: "GET", Path: "/flags/dark-mode"})
	if b := got.Body.(map[string]any); b["rollout_percent"] != float64(100) || b["enabled"] != true {
		t.Fatalf("v1 data under v2: %v", got.Body)
	}
	if r, _ := Call(ctx, prod.URL, HTTPCall{Method: "DELETE", Path: "/flags/dark-mode"}); r.Status != 409 {
		t.Fatalf("new rule not live: %+v", r)
	}

	// Rewind: v1 is back, with the data intact.
	if _, err := rt.Undo(ctx, "release-v2", "rewound the rollout decision"); err != nil {
		t.Fatal(err)
	}
	if router.Live() != v1 {
		t.Fatal("v1 is not live after rewinding v2")
	}
	if r, _ := Call(ctx, prod.URL, HTTPCall{Method: "DELETE", Path: "/flags/dark-mode"}); r.Status != 204 {
		t.Fatalf("v1 behaviour not restored: %+v", r)
	}
	if r, _ := Call(ctx, prod.URL, HTTPCall{Method: "GET", Path: "/flags/new-search"}); r.Status != 200 {
		t.Fatalf("data lost across versions: %+v", r)
	}
}

// forgetful generates the right code, then breaks it the way a careless
// coder (or model) might: records loaded from disk don't get defaults.
type forgetful struct{}

func (forgetful) Code(ctx context.Context, s ServiceSpec, prev map[string]string, f []Result) (map[string]string, error) {
	files, err := Codegen{}.Code(ctx, s, prev, f)
	if err != nil {
		return nil, err
	}
	files["main.go"] = strings.Replace(files["main.go"], "r := defaults() // records written by an older version get today's defaults", "var r Flag", 1)
	return files, nil
}

func TestStateDiffCatchesAMigrationBugTheExamplesMiss(t *testing.T) {
	ctx := context.Background()
	v1 := build(t, spec(t, "flags-v1.json"))
	bad, err := (&Factory{Root: t.TempDir(), Coder: forgetful{}}).Build(ctx, spec(t, "flags-v2.json"))
	if err != nil {
		t.Fatalf("the bug is invisible to the examples, so the build should pass: %v", err)
	}

	router := &Router{DataPath: filepath.Join(t.TempDir(), "flags.json")}
	defer router.Stop()
	prod := httptest.NewServer(router)
	defer prod.Close()
	rt := reversible.New()
	rt.Execute(ctx, reversible.Intent{ID: "r1", Effects: []reversible.Effect{router.Release(v1)}})
	for _, c := range teamTraffic[:5] {
		Call(ctx, prod.URL, c)
	}

	replay, _ := Diff(ctx, router.Traffic(), v1, bad)
	if len(replay.Unexpected()) != 0 {
		t.Fatalf("replay from empty state can't see this bug, and shouldn't claim to:\n%s", replay)
	}
	sd, err := DiffState(ctx, router.DataPath, v1, bad)
	if err != nil {
		t.Fatal(err)
	}
	if len(sd.Unexpected()) == 0 || !strings.Contains(sd.String(), `"rollout_percent":0`) {
		t.Fatalf("state diff missed existing flags silently dropping to 0%% rollout:\n%s", sd)
	}
}

// chatty changes an error message nobody asked to change.
type chatty struct{}

func (chatty) Code(ctx context.Context, s ServiceSpec, prev map[string]string, f []Result) (map[string]string, error) {
	files, _ := Codegen{}.Code(ctx, s, prev, f)
	files["main.go"] = strings.Replace(files["main.go"], `already exists`, `is taken, pick another`, 1)
	return files, nil
}

func TestUnexplainedChangesAreFlagged(t *testing.T) {
	ctx := context.Background()
	v1 := build(t, spec(t, "flags-v1.json"))
	s := spec(t, "flags-v1.json")
	s.Purpose += " " // same behaviour intended, so any change is unexplained
	drift, err := (&Factory{Root: t.TempDir(), Coder: chatty{}}).Build(ctx, s)
	if err != nil {
		t.Fatal(err)
	}
	traffic := []Exchange{
		{Request: HTTPCall{Method: "POST", Path: "/flags", Body: map[string]any{"key": "a", "owner": "x"}}},
		{Request: HTTPCall{Method: "POST", Path: "/flags", Body: map[string]any{"key": "a", "owner": "y"}}},
	}
	d, err := Diff(ctx, traffic, v1, drift)
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Unexpected()) != 1 || !strings.Contains(d.String(), "UNEXPLAINED") {
		t.Fatalf("diff:\n%s", d)
	}
}

func TestDownstreamChangesAreTracedToTheirCause(t *testing.T) {
	ctx := context.Background()
	v1, v2 := build(t, spec(t, "flags-v1.json")), build(t, spec(t, "flags-v2.json"))
	traffic := []Exchange{
		{Request: HTTPCall{Method: "POST", Path: "/flags", Body: map[string]any{"key": "a", "owner": "x"}}},
		{Request: HTTPCall{Method: "PATCH", Path: "/flags/a", Body: map[string]any{"enabled": true}}},
		{Request: HTTPCall{Method: "DELETE", Path: "/flags/a"}}, // refused under v2
		{Request: HTTPCall{Method: "GET", Path: "/flags/a"}},    // 404 vs 200: follows from the refusal
		{Request: HTTPCall{Method: "GET", Path: "/flags"}},      // [] vs [a]: follows from the refusal
		{Request: HTTPCall{Method: "POST", Path: "/flags", Body: map[string]any{"key": "b", "owner": "y"}}},
	}
	d, err := Diff(ctx, traffic, v1, v2)
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Unexpected()) != 0 {
		t.Fatalf("diff:\n%s", d)
	}
	n := 0
	for _, c := range d.Changes {
		if strings.HasPrefix(c.Because, "follows from earlier change (new rule") {
			n++
		}
	}
	if n != 2 {
		t.Fatalf("expected 2 downstream changes traced to the new rule:\n%s", d)
	}
}
