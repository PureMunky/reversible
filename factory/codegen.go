package factory

import (
	"context"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Contract is what every generated service must do, whoever writes it.
// It is given verbatim to model coders.
const Contract = `- package main, a single file main.go, Go standard library only
- listen on the address in env ADDR (default "127.0.0.1:0") and print exactly one line "LISTENING http://<host:port>" to stdout once listening
- if env DATA is set, load all records from that JSON file (a JSON array) at start and rewrite it after every change; ignore unknown fields; a missing file means empty; a record missing a field gets that field's default (data written by an older version must keep working)
- manage one resource at /<plural>: POST /<plural> creates (201 + record), GET /<plural> lists all sorted by key (200), GET /<plural>/{key} (200 or 404), PATCH /<plural>/{key} partially updates (200), DELETE /<plural>/{key} (204)
- apply each field's default to fields missing on create; reject unknown fields, missing required fields, wrong types and invalid values with 400; a duplicate key on create is 409; changing the key on PATCH is 400; a missing record is 404; a delete refused by a rule is 409
- every error response is JSON {"error": "<message>"}; GET /healthz returns 200
- the spec's examples are the contract: they will be run in order against a fresh instance and every one must pass`

// Coder turns intent into source files. A previous attempt and the
// examples it failed are passed back so a coder can repair its own work.
type Coder interface {
	Code(ctx context.Context, spec ServiceSpec, previous map[string]string, failures []Result) (map[string]string, error)
}

// Codegen is a deterministic coder: it compiles the spec directly into Go.
// It needs no model, covers exactly what the spec language can express,
// and is how the factory runs offline and in tests.
type Codegen struct{}

func (Codegen) Code(_ context.Context, s ServiceSpec, _ map[string]string, _ []Result) (map[string]string, error) {
	if qs := s.Check(); !Ready(qs) {
		return nil, fmt.Errorf("spec is not ready: %v", qs[0])
	}
	return map[string]string{"main.go": generate(s)}, nil
}

func goName(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func goType(t string) string {
	switch t {
	case "bool":
		return "bool"
	case "int":
		return "int64"
	case "number":
		return "float64"
	}
	return "string"
}

func goLiteral(t string, v any) string {
	switch t {
	case "string":
		return strconv.Quote(fmt.Sprint(v))
	case "bool":
		return fmt.Sprint(v)
	case "int":
		f, _ := v.(float64)
		return strconv.FormatInt(int64(f), 10)
	default:
		f, _ := v.(float64)
		return strconv.FormatFloat(f, 'g', -1, 64)
	}
}

func generate(s ServiceSpec) string {
	r := s.Resource
	typ := goName(r.Name)
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("// Code generated by reversible/factory from intent %q (spec %s). DO NOT EDIT.\n", s.Service, s.Hash())
	w("// This file is a cache: change the intent, not the code.\n\n")
	w("package main\n\n")
	w("import (\n\t\"encoding/json\"\n\t\"fmt\"\n\t\"net\"\n\t\"net/http\"\n\t\"os\"\n\t\"regexp\"\n\t\"sort\"\n\t\"sync\"\n)\n\n")
	w("var _ = regexp.MustCompile\n\n")

	w("// %s: %s\n", typ, oneLine(s.Purpose))
	w("type %s struct {\n", typ)
	for _, f := range r.Fields {
		w("\t%s %s `json:%q`\n", goName(f.Name), goType(f.Type), f.Name)
	}
	w("}\n\n")

	w("var known = map[string]bool{")
	for _, f := range r.Fields {
		w("%q: true, ", f.Name)
	}
	w("}\n\n")

	for _, f := range r.Fields {
		if f.Pattern != "" {
			w("var %sPattern = regexp.MustCompile(%s)\n", f.Name, strconv.Quote(f.Pattern))
		}
	}
	w("\nfunc defaults() %s {\n\tvar r %s\n", typ, typ)
	for _, f := range r.Fields {
		if f.Default != nil {
			w("\tr.%s = %s\n", goName(f.Name), goLiteral(f.Type, f.Default))
		}
	}
	w("\treturn r\n}\n\n")

	w("func validate(r %s) string {\n", typ)
	for _, f := range r.Fields {
		g := goName(f.Name)
		why := ""
		if f.Why != "" {
			why = " (" + f.Why + ")"
		}
		switch f.Type {
		case "string":
			if f.Required {
				w("\tif r.%s == \"\" {\n\t\treturn %q\n\t}\n", g, f.Name+" is required")
			}
			if f.Pattern != "" {
				w("\tif r.%s != \"\" && !%sPattern.MatchString(r.%s) {\n\t\treturn %q\n\t}\n", g, f.Name, g, fmt.Sprintf("%s must match %s%s", f.Name, f.Pattern, why))
			}
			if len(f.Enum) > 0 {
				var conds []string
				for _, e := range f.Enum {
					conds = append(conds, fmt.Sprintf("r.%s == %q", g, e))
				}
				w("\tif r.%s != \"\" && !(%s) {\n\t\treturn %q\n\t}\n", g, strings.Join(conds, " || "), fmt.Sprintf("%s must be one of %s%s", f.Name, strings.Join(f.Enum, ", "), why))
			}
		case "int", "number":
			if f.Min != nil {
				w("\tif float64(r.%s) < %v {\n\t\treturn %q\n\t}\n", g, *f.Min, fmt.Sprintf("%s must be at least %g%s", f.Name, *f.Min, why))
			}
			if f.Max != nil {
				w("\tif float64(r.%s) > %v {\n\t\treturn %q\n\t}\n", g, *f.Max, fmt.Sprintf("%s must be at most %g%s", f.Name, *f.Max, why))
			}
		}
	}
	w("\treturn \"\"\n}\n\n")

	var required []string
	for _, f := range r.Fields {
		if f.Required {
			required = append(required, strconv.Quote(f.Name))
		}
	}
	sort.Strings(required)
	w("var required = []string{%s}\n\n", strings.Join(required, ", "))

	keyGo := goName(r.Key)
	w(`var (
	mu       sync.Mutex
	store    = map[string]%[1]s{}
	dataPath = os.Getenv("DATA")
)

func load() {
	if dataPath == "" {
		return
	}
	b, err := os.ReadFile(dataPath)
	if err != nil {
		return
	}
	var all []json.RawMessage
	if json.Unmarshal(b, &all) == nil {
		for _, raw := range all {
			r := defaults() // records written by an older version get today's defaults
			if json.Unmarshal(raw, &r) == nil {
				store[r.%[2]s] = r
			}
		}
	}
}

func save() {
	if dataPath == "" {
		return
	}
	b, _ := json.MarshalIndent(sorted(), "", "  ")
	tmp := dataPath + ".tmp"
	if os.WriteFile(tmp, b, 0o644) == nil {
		os.Rename(tmp, dataPath)
	}
}

func sorted() []%[1]s {
	out := make([]%[1]s, 0, len(store))
	for _, r := range store {
		out = append(out, r)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].%[2]s < out[j].%[2]s })
	return out
}

func reply(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if v != nil {
		json.NewEncoder(w).Encode(v)
	}
}

func fail(w http.ResponseWriter, status int, msg string) {
	reply(w, status, map[string]string{"error": msg})
}

func body(r *http.Request) (map[string]json.RawMessage, string) {
	var raw map[string]json.RawMessage
	if err := json.NewDecoder(r.Body).Decode(&raw); err != nil || raw == nil {
		return nil, "body must be a JSON object"
	}
	for k := range raw {
		if !known[k] {
			return nil, fmt.Sprintf("unknown field %%q", k)
		}
	}
	return raw, ""
}

func apply(rec *%[1]s, raw map[string]json.RawMessage) string {
	b, _ := json.Marshal(raw)
	if err := json.Unmarshal(b, rec); err != nil {
		return "invalid value: " + err.Error()
	}
	return ""
}

`, typ, keyGo)

	base := "/" + r.Plural
	w("func main() {\n\tmux := http.NewServeMux()\n")
	w("\tmux.HandleFunc(\"GET /healthz\", func(w http.ResponseWriter, r *http.Request) { reply(w, 200, map[string]string{\"status\": \"ok\"}) })\n\n")

	w(`	mux.HandleFunc("POST %[1]s", func(w http.ResponseWriter, r *http.Request) {
		raw, msg := body(r)
		if msg != "" {
			fail(w, 400, msg)
			return
		}
		for _, f := range required {
			if _, ok := raw[f]; !ok {
				fail(w, 400, f+" is required")
				return
			}
		}
		rec := defaults()
		if msg := apply(&rec, raw); msg != "" {
			fail(w, 400, msg)
			return
		}
		if msg := validate(rec); msg != "" {
			fail(w, 400, msg)
			return
		}
		mu.Lock()
		defer mu.Unlock()
		if _, exists := store[rec.%[2]s]; exists {
			fail(w, 409, fmt.Sprintf("%[3]s %%s already exists", rec.%[2]s))
			return
		}
		store[rec.%[2]s] = rec
		save()
		reply(w, 201, rec)
	})

	mux.HandleFunc("GET %[1]s", func(w http.ResponseWriter, r *http.Request) {
		mu.Lock()
		defer mu.Unlock()
		reply(w, 200, sorted())
	})

	mux.HandleFunc("GET %[1]s/{key}", func(w http.ResponseWriter, r *http.Request) {
		mu.Lock()
		defer mu.Unlock()
		rec, ok := store[r.PathValue("key")]
		if !ok {
			fail(w, 404, fmt.Sprintf("%[3]s %%s not found", r.PathValue("key")))
			return
		}
		reply(w, 200, rec)
	})

	mux.HandleFunc("PATCH %[1]s/{key}", func(w http.ResponseWriter, r *http.Request) {
		key := r.PathValue("key")
		raw, msg := body(r)
		if msg != "" {
			fail(w, 400, msg)
			return
		}
		mu.Lock()
		defer mu.Unlock()
		rec, ok := store[key]
		if !ok {
			fail(w, 404, fmt.Sprintf("%[3]s %%s not found", key))
			return
		}
		if msg := apply(&rec, raw); msg != "" {
			fail(w, 400, msg)
			return
		}
		if rec.%[2]s != key {
			fail(w, 400, "%[4]s cannot be changed")
			return
		}
		if msg := validate(rec); msg != "" {
			fail(w, 400, msg)
			return
		}
		store[key] = rec
		save()
		reply(w, 200, rec)
	})

	mux.HandleFunc("DELETE %[1]s/{key}", func(w http.ResponseWriter, r *http.Request) {
		key := r.PathValue("key")
		mu.Lock()
		defer mu.Unlock()
		rec, ok := store[key]
		if !ok {
			fail(w, 404, fmt.Sprintf("%[3]s %%s not found", key))
			return
		}
		_ = rec
`, base, keyGo, r.Name, r.Key)

	for _, rule := range r.Rules {
		c := rule.ForbidDeleteWhen
		if c == nil {
			continue
		}
		var field Field
		for _, f := range r.Fields {
			if f.Name == c.Field {
				field = f
			}
		}
		msg := fmt.Sprintf("cannot delete a %s while %s is %v", r.Name, c.Field, c.Equals)
		if rule.Why != "" {
			msg += " (" + rule.Why + ")"
		}
		w("\t\tif rec.%s == %s {\n\t\t\tfail(w, 409, %q)\n\t\t\treturn\n\t\t}\n", goName(c.Field), goLiteral(field.Type, c.Equals), msg)
	}
	w(`		delete(store, key)
		save()
		reply(w, 204, nil)
	})

	addr := os.Getenv("ADDR")
	if addr == "" {
		addr = "127.0.0.1:0"
	}
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	load()
	fmt.Printf("LISTENING http://%%s\n", ln.Addr())
	http.Serve(ln, mux)
}
`)
	return b.String()
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
